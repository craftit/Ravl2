  OptimiseBobyqa::OptimiseBobyqa(std::size_t maxEvaluations, double rhoBegin, double rhoEnd,
                                 std::size_t numInterpolationPoints, bool verbose)
      : Optimise(verbose),
        mMaxEvaluations(maxEvaluations),
        mRhoBegin(rhoBegin),
        mRhoEnd(rhoEnd),
        mNumInterpolationPoints(numInterpolationPoints)
  {
    validate();
  }

  OptimiseBobyqa::OptimiseBobyqa(Configuration &config)
      : Optimise(config),
        mMaxEvaluations(config.getUnsigned("maxEvaluations", "Limit on the number of cost function evaluations", 1000u, 1u, 100000000u)),
        mRhoBegin(config.getNumber<double>("rhoBegin", "Initial trust region radius, about a tenth of the largest expected change to a variable", 0.1, 1e-12, 1e12)),
        mRhoEnd(config.getNumber<double>("rhoEnd", "Final trust region radius, the accuracy required in the variables", 1e-4, 1e-15, 1e12)),
        mNumInterpolationPoints(config.getUnsigned("numInterpolationPoints", "Number of interpolation points, in [n+2,(n+1)(n+2)/2]; 0 selects 2n+1", 0u, 0u, 1000000u))
  {
    validate();
  }

  void OptimiseBobyqa::validate() const
  {
    if(!(mRhoBegin > 0.0) || !(mRhoEnd > 0.0) || !(mRhoEnd <= mRhoBegin)) {
      throw std::invalid_argument(fmt::format("OptimiseBobyqa: need 0 < rhoEnd <= rhoBegin, got rhoBegin {} rhoEnd {}", mRhoBegin, mRhoEnd));
    }
    if(mMaxEvaluations < 1) {
      throw std::invalid_argument("OptimiseBobyqa: maxEvaluations must be at least 1");
    }
  }

  BobyqaResult<OptimiseBobyqa::RealT> OptimiseBobyqa::minimiseDetailed(
    const CostDomain<RealT> &domain,
    const std::function<RealT(const VectorT<RealT> &)> &func,
    const VectorT<RealT> &start) const
  {
    if(domain.empty()) {
      throw std::invalid_argument("OptimiseBobyqa: empty domain");
    }
    if(domain.min().size() != domain.max().size()) {
      throw std::invalid_argument("OptimiseBobyqa: domain min and max differ in size");
    }
    const VectorT<RealT> startPoint = start.size() == 0 ? domain.mid() : start;
    if(startPoint.size() != domain.dim()) {
      throw std::invalid_argument(fmt::format("OptimiseBobyqa: start has {} dimensions, domain has {}", startPoint.size(), domain.dim()));
    }

    // The core works in double; evaluate the user's float function at the float rounding of each point.
    VectorT<RealT> point(domain.dim());
    const std::function<double(const VectorT<double> &)> costDouble = [&func, &point](const VectorT<double> &x) {
      point = x.cast<RealT>();
      return static_cast<double>(func(point));
    };

    const BobyqaResult<double> core = bobyqaMinimise(costDouble, startPoint.cast<double>(), domain.min().cast<double>(),
                                                     domain.max().cast<double>(), mNumInterpolationPoints, mRhoBegin,
                                                     mRhoEnd, mMaxEvaluations);

    if(core.status != BobyqaStatus::Converged) {
      SPDLOG_DEBUG("OptimiseBobyqa: stopped early ({}) after {} evaluations, best cost {}", toString(core.status),
                   core.evaluations, core.cost);
    }
    if(mVerbose) {
      SPDLOG_INFO("OptimiseBobyqa: {} after {} evaluations, cost {}", toString(core.status), core.evaluations, core.cost);
    }

    BobyqaResult<RealT> result;
    result.x = core.x.cast<RealT>();
    result.cost = static_cast<RealT>(core.cost);
    result.evaluations = core.evaluations;
    result.status = core.status;
    return result;
  }

  std::tuple<VectorT<OptimiseBobyqa::RealT>, OptimiseBobyqa::RealT> OptimiseBobyqa::minimise(
    const CostDomain<RealT> &domain,
    const std::function<RealT(const VectorT<RealT> &)> &func,
    const VectorT<RealT> &start) const
  {
    BobyqaResult<RealT> result = minimiseDetailed(domain, func, start);
    return std::make_tuple(std::move(result.x), result.cost);
  }

